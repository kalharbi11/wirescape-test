"""A106 scratch preparation: mock the native build, never a real device."""
import json
from pathlib import Path
from unittest.mock import patch

from test_wstest import PresentationTests, write, git
import wstest


class MB1Tests(PresentationTests):
    # Do not inherit the pre-MB1 presentation test cases into this fixture.
    def setUp(self):
        super().setUp()
        self.inventory = '{\n "golden_set": ["essentials.existing"],\n "experimental": [],\n "note": "preserve  spaces"\n}\n'
        write(self.upstream / "tools/mb1/test_wire_describe.py", "# SPDX-License-Identifier: GPL-3.0-only\n")
        write(self.upstream / "bench/module_sets.json", self.inventory)
        write(self.upstream / "tools/foundation/fixtures/known_module_ids.txt",
              "# SPDX-License-Identifier: GPL-3.0-only\n"
              "# Generated by tools/gen_ui_catalogue.py from wire-describe; never remove IDs.\n"
              "essentials.existing\n")
        write(self.upstream / wstest.UI_GENERATOR, self.GENERATOR + '''
import argparse
parser = argparse.ArgumentParser()
parser.add_argument("--describe", required=True, type=pathlib.Path)
args = parser.parse_args()
assert args.describe.is_file()
ids = sorted(m["id"] for m in d["modules"])
(root / "tools/foundation/fixtures/known_module_ids.txt").write_bytes(
    ("# SPDX-License-Identifier: GPL-3.0-only\\n"
     "# Generated by tools/gen_ui_catalogue.py from wire-describe; never remove IDs.\\n"
     + "".join(i + "\\n" for i in ids)).encode("utf-8"))
''')
        git(self.upstream, "add", ".")
        git(self.upstream, "commit", "-qm", "MB1")
        self.sha = git(self.upstream, "rev-parse", "HEAD").strip()
        write(self.root / "LAB_PIN", f"repo=example/lab\ncommit={self.sha}\npinned=2026-11-27\n")
        self.lab = wstest.Lab(self.root)
        self.lab.fetch()

    def fake_build(self, lab, source, build_dir, targets, sanitize, config):
        self.assertEqual(targets, ["wire-describe"])
        self.assertTrue((source / "modules/thing/dsp.h").is_file())
        write(build_dir / ("wire-describe" + wstest.EXE), "fake descriptor")
        return True, ""

    def test_a106_new_module(self):
        m = self.thing({"id": "test.thing"})
        scratch = self.root / "build/scratch"
        real_run = wstest.run

        def run(cmd, *args, **kwargs):
            if Path(cmd[0]).name == "wire-describe" + wstest.EXE:
                import subprocess
                return subprocess.CompletedProcess(cmd, 0, json.dumps(
                    {"modules": [{"id": "essentials.existing"}, {"id": "test.thing"}]}), "")
            return real_run(cmd, *args, **kwargs)

        with patch.object(wstest, "cmake_build", side_effect=self.fake_build) as build, \
             patch.object(wstest, "run", side_effect=run):
            tree = wstest.prepare_tree(self.lab, scratch, [m])
        build.assert_called_once()
        inventory = (scratch / "bench/module_sets.json").read_text()
        self.assertEqual(json.loads(inventory)["experimental"], ["test.thing"])
        self.assertEqual(inventory.replace('"test.thing"', ''), self.inventory)
        wstest.verify_scratch(scratch, tree)
        write(scratch / "bench/module_sets.json", self.inventory)
        with self.assertRaises(wstest.Refused):
            wstest.verify_scratch(scratch, tree)

    def test_a106_override_inventory_is_byte_identical(self):
        from test_wstest import module
        folder = module(self.root / "modules/existing", "existing::Existing")
        override = wstest.Module("existing", folder, "override")
        self.assertEqual(wstest.bench_inventory(self.lab.dir, [override]),
                         self.inventory.encode("utf-8"))

    def test_a106_append_preserves_existing_inventory_bytes(self):
        source = self.lab.dir / "bench/module_sets.json"
        original = self.inventory.replace('[]', '[ "old.id" ]')
        write(source, original)
        m = self.thing({"id": "test.thing"})
        result = wstest.bench_inventory(self.lab.dir, [m]).decode("utf-8")
        self.assertEqual(result, original.replace('"old.id"', '"old.id", "test.thing"'))

    def test_a106_generator_known_ids_must_match_descriptor(self):
        m = self.thing({"id": "test.thing"})
        real_run = wstest.run

        def run(cmd, *args, **kwargs):
            if Path(cmd[0]).name == "wire-describe" + wstest.EXE:
                import subprocess
                return subprocess.CompletedProcess(cmd, 0, json.dumps(
                    {"modules": [{"id": "essentials.existing"}, {"id": "test.thing"}]}), "")
            return real_run(cmd, *args, **kwargs)

        def corrupt(dest, describe):
            write(dest / "tools/foundation/fixtures/known_module_ids.txt", "not the descriptor\n")
            return b"[]\n"

        with patch.object(wstest, "cmake_build", side_effect=self.fake_build), \
             patch.object(wstest, "run", side_effect=run), \
             patch.object(wstest, "run_ui_generator", side_effect=corrupt):
            with self.assertRaisesRegex(wstest.Refused, "does not match scratch wire-describe"):
                wstest.prepare_tree(self.lab, self.root / "build/scratch", [m])

    def test_a106_missing_target_fails_closed(self):
        m = self.thing({"id": "test.thing"})
        with patch.object(wstest, "cmake_build", return_value=(False, "missing wire-describe target")):
            with self.assertRaisesRegex(wstest.Refused, "wire-describe"):
                wstest.prepare_tree(self.lab, self.root / "build/scratch", [m])


# PresentationTests owns the old-pin cases; this subclass only runs A106 cases.
for _name in dir(PresentationTests):
    if _name.startswith("test_"):
        setattr(MB1Tests, _name, None)
del PresentationTests
